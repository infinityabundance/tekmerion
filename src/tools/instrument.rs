//! Wrap every top-level `let` in `tools/bridge.ml` so a fresh HOL Light process
//! reports each lemma/binding separately.
//!
//! Port of `research/receipts/bridge/instrument.py`. Each phrase `P` of the form
//! `let NAME = EXPR` becomes
//!
//! ```text
//! let NAME =
//!   bridge_check "NAME" (fun () -> (
//! P
//!    in NAME));;
//! ```
//!
//! A failing phrase leaves the binding undefined, so later dependants fail too —
//! which is the wanted signal. No statement or tactic is rewritten.
//!
//! Output is byte-identical to the Python original (header prose, phrase count
//! and `sha256(source)` included). **Not on the verdict path.**

use std::fs;

use crate::tools::sha256;

const USAGE: &str = "\
usage: instrument <src.ml> <out.ml>

  Wraps every top-level `let NAME = ...;;` phrase so it reports through
  `bridge_check`. The output names `sha256(source)` and the phrase count.
";

/// `\s` for the identifier regex; ASCII whitespace, matching the source files.
fn is_space(b: u8) -> bool {
    matches!(b, b' ' | b'\t' | b'\n' | b'\r' | 0x0b | 0x0c)
}

fn is_word(b: u8) -> bool {
    b.is_ascii_alphanumeric() || b == b'_'
}

/// Split on `;;` + optional spaces/tabs + newline-or-end-of-input.
///
/// This is `re.split(r";;[ \t]*(?:\n|$)", src)` restricted to the inputs the
/// corpus contains (LF line endings): because `\n` is tried before `$`, the
/// zero-width alternative only fires at true end-of-input, so the `` ;; `` and
/// the following newline are always consumed together.
pub fn split_chunks(src: &str) -> Vec<&str> {
    let bytes = src.as_bytes();
    let mut out = Vec::new();
    let mut start = 0usize;
    let mut i = 0usize;
    while i + 1 < bytes.len() {
        if bytes[i] == b';' && bytes[i + 1] == b';' {
            let mut j = i + 2;
            while j < bytes.len() && (bytes[j] == b' ' || bytes[j] == b'\t') {
                j += 1;
            }
            if j == bytes.len() {
                out.push(&src[start..i]);
                start = j;
                i = j;
                continue;
            }
            if bytes[j] == b'\n' {
                out.push(&src[start..i]);
                start = j + 1;
                i = j + 1;
                continue;
            }
        }
        i += 1;
    }
    out.push(&src[start..]);
    out
}

/// First `\blet\s+(?:rec\s+)?([A-Za-z_][A-Za-z0-9_]*)` match, if any.
pub fn find_let_name(chunk: &str) -> Option<&str> {
    let bytes = chunk.as_bytes();
    let name_at = |mut j: usize| -> Option<&str> {
        if j < bytes.len() && (bytes[j].is_ascii_alphabetic() || bytes[j] == b'_') {
            let start = j;
            j += 1;
            while j < bytes.len() && is_word(bytes[j]) {
                j += 1;
            }
            Some(&chunk[start..j])
        } else {
            None
        }
    };

    let mut i = 0usize;
    while i + 3 <= bytes.len() {
        let boundary_before = i == 0 || !is_word(bytes[i - 1]);
        if &bytes[i..i + 3] == b"let" && boundary_before {
            let mut j = i + 3;
            let ws_start = j;
            while j < bytes.len() && is_space(bytes[j]) {
                j += 1;
            }
            if j > ws_start {
                // `(?:rec\s+)?` is greedy: try the `rec` branch first, then
                // fall back to treating `rec` as the name itself.
                if bytes[j..].starts_with(b"rec") {
                    let mut k = j + 3;
                    let rec_ws = k;
                    while k < bytes.len() && is_space(bytes[k]) {
                        k += 1;
                    }
                    if k > rec_ws {
                        if let Some(name) = name_at(k) {
                            return Some(name);
                        }
                    }
                }
                if let Some(name) = name_at(j) {
                    return Some(name);
                }
            }
        }
        i += 1;
    }
    None
}

fn header(src_label: &str, digest: &str) -> String {
    let mut s = String::new();
    s.push_str("(* GENERATED by research/receipts/bridge/instrument.py from ");
    s.push_str(src_label);
    s.push_str(".\n   sha256(source) = ");
    s.push_str(digest);
    s.push_str(
        "\n   Statements and tactics are byte-identical; only per-phrase reporting is\n   added.  Do not edit. *)\n",
    );
    s.push_str(
        "let bridge_check name (f:unit->'a) =\n  try\n    let v = f () in\n    Printf.printf \"BRIDGE_CHECK %s OK\\n%!\" name; v\n  with e ->\n    Printf.printf \"BRIDGE_CHECK %s FAIL: %s\\n%!\" name (Printexc.to_string e);\n    failwith (\"BRIDGE_CHECK_FAILED:\" ^ name);;\n",
    );
    s
}

/// Render the instrumented source. Returns the output text and the number of
/// non-blank phrases (the figure the original prints).
pub fn instrument_text(src: &str, src_label: &str) -> (String, usize) {
    let digest = sha256::hex(src.as_bytes());
    let chunks = split_chunks(src);
    let mut out = header(src_label, &digest);
    let mut phrases = 0usize;

    for chunk in &chunks {
        if chunk.trim().is_empty() {
            continue;
        }
        phrases += 1;
        match find_let_name(chunk) {
            None => {
                out.push_str(chunk);
                out.push_str(";;\n");
            }
            Some(name) => {
                let body = chunk.trim_end();
                out.push_str("let ");
                out.push_str(name);
                out.push_str(" =\n  bridge_check \"");
                out.push_str(name);
                out.push_str("\" (fun () -> (\n");
                out.push_str(body);
                out.push_str("\n   in ");
                out.push_str(name);
                out.push_str("));;\n");
            }
        }
    }

    (out, phrases)
}

/// CLI entry point. `args` excludes the program name.
pub fn run(args: &[String]) -> i32 {
    if args.len() == 1 && matches!(args[0].as_str(), "-h" | "--help") {
        print!("{USAGE}");
        return 0;
    }
    if args.len() != 2 {
        eprint!("{USAGE}");
        return 2;
    }
    let src = match fs::read_to_string(&args[0]) {
        Ok(s) => s,
        Err(e) => {
            eprintln!("ERROR {}: {e}", args[0]);
            return 2;
        }
    };
    let (out, phrases) = instrument_text(&src, &args[0]);
    if let Err(e) = fs::write(&args[1], out.as_bytes()) {
        eprintln!("ERROR {}: {e}", args[1]);
        return 2;
    }
    println!(
        "wrote {} sha256={} phrases={}",
        args[1],
        sha256::hex(src.as_bytes()),
        phrases
    );
    0
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn splits_on_double_semicolon_and_keeps_tail() {
        assert_eq!(split_chunks("a;;\nb;;\n"), vec!["a", "b", ""]);
        assert_eq!(split_chunks("a;;  \nb;;"), vec!["a", "b", ""]);
        assert_eq!(split_chunks("a;;b"), vec!["a;;b"]);
    }

    #[test]
    fn finds_let_and_optional_rec() {
        assert_eq!(find_let_name("let foo = 1"), Some("foo"));
        assert_eq!(find_let_name("let rec bar = 1"), Some("bar"));
        assert_eq!(find_let_name("(* no binding *) print_string \"x\""), None);
        assert_eq!(find_let_name("outlet = 1"), None);
    }

    #[test]
    fn instrumented_three_phrase_fixture() {
        let src = "let a = 1;;\n\nlet rec b = 2;;\nprint_string \"x\";;\n";
        let (out, phrases) = instrument_text(src, "sample.ml");
        assert_eq!(phrases, 3, "{out}");
        assert!(out.starts_with(
            "(* GENERATED by research/receipts/bridge/instrument.py from sample.ml.\n"
        ));
        assert!(
            out.contains("let a =\n  bridge_check \"a\" (fun () -> (\nlet a = 1\n   in a));;\n")
        );
        // Leading blank line of the second chunk is preserved, like the original.
        assert!(out.contains(
            "let b =\n  bridge_check \"b\" (fun () -> (\n\nlet rec b = 2\n   in b));;\n"
        ));
        assert!(out.ends_with("print_string \"x\";;\n"));
    }
}
