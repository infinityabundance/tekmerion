#!/usr/bin/env python3
"""instrument.py -- mechanically wrap every top-level `let` in tools/bridge.ml
so a fresh HOL Light process reports each lemma/binding separately.

The transformation never rewrites a statement or a tactic: each phrase P of the
form `let NAME = EXPR` becomes

    let NAME = bridge_check "NAME" (fun () -> (P in NAME));;

so a failure is printed and the binding is left undefined (later dependants then
fail too, which is the wanted signal).  Run with:

    python3 instrument.py <bridge.ml> <out.ml>
"""

import hashlib
import re
import sys

NAME_RE = re.compile(r"\blet\s+(?:rec\s+)?([A-Za-z_][A-Za-z0-9_]*)")
SPLIT_RE = re.compile(r";;[ \t]*(?:\n|$)")

HEADER = """(* GENERATED by research/receipts/bridge/instrument.py from {src}.
   sha256(source) = {digest}
   Statements and tactics are byte-identical; only per-phrase reporting is
   added.  Do not edit. *)
let bridge_check name (f:unit->'a) =
  try
    let v = f () in
    Printf.printf "BRIDGE_CHECK %s OK\\n%!" name; v
  with e ->
    Printf.printf "BRIDGE_CHECK %s FAIL: %s\\n%!" name (Printexc.to_string e);
    failwith ("BRIDGE_CHECK_FAILED:" ^ name);;
"""


def main(src_path, out_path):
    with open(src_path, "r", encoding="utf-8") as fh:
        src = fh.read()
    digest = hashlib.sha256(src.encode("utf-8")).hexdigest()

    chunks = SPLIT_RE.split(src)
    out = [HEADER.format(src=src_path, digest=digest)]
    for chunk in chunks:
        if chunk.strip() == "":
            continue
        m = NAME_RE.search(chunk)
        if m is None:
            out.append(chunk + ";;\n")
            continue
        name = m.group(1)
        body = chunk.rstrip()
        if not body.endswith(";;"):
            body = body  # trailing ';;' removed by the split
        out.append(
            f'let {name} =\n'
            f'  bridge_check "{name}" (fun () -> (\n'
            f'{body}\n'
            f'   in {name}));;\n'
        )
    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write("".join(out))
    print(f"wrote {out_path} sha256={digest} phrases={len([c for c in chunks if c.strip()])}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
