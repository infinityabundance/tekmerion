(* ========================================================================= *)
(* W1 gate: capture the ARM post-simulation goal state.                       *)
(*                                                                           *)
(* This driver is deliberately independent of tools/derive_steps.py.  It     *)
(* knows only the three machine-code descriptions (from the ELF objects) and *)
(* the tactic prefix of each proof up to and including the simulation call.  *)
(* The accumulate lists arrive in $W1_LISTS, generated by tools/w1_gate.py:  *)
(* the "human" lists are extracted from the proof files for comparison only, *)
(* the "derived" lists come from tools/derive_steps.derive_accumulate, and   *)
(* the "diag" lists add a flag-liveness closure to locate any difference.     *)
(*                                                                           *)
(* For each (operation, list) pair the driver sets the theorem statement,    *)
(* runs the prefix, and dumps every remaining subgoal (assumptions and       *)
(* conclusion, canonicalised) plus an MD5.  It then closes the proof from    *)
(* the captured derived state by running the remaining human tactic chain.   *)
(* ========================================================================= *)

needs "arm/proofs/base.ml";;

let w1_out = Sys.getenv "W1_OUT";;
let w1_lists = Sys.getenv "W1_LISTS";;
loadt w1_lists;;

let out = open_out w1_out;;

(* Collapse formatting whitespace so a term's printed form is stable. *)
let canon s =
  let b = Buffer.create (String.length s) in
  let sp = ref true in
  String.iter
    (fun c ->
      if c = ' ' || c = '\n' || c = '\t' || c = '\r' then
        (if not !sp then Buffer.add_char b ' '; sp := true)
      else (Buffer.add_char b c; sp := false))
    s;
  Buffer.contents b;;

let md5 s = Digest.to_hex (Digest.string s);;

let dump_goals tag gl =
  Printf.fprintf out "BEGIN %s COUNT %d\n" tag (List.length gl);
  List.iteri
    (fun i (asl,w) ->
      Printf.fprintf out "GOAL %d ASMS %d\n" i (List.length asl);
      List.iter
        (fun (_,th) -> Printf.fprintf out "ASM %s\n" (canon (string_of_term (concl th))))
        asl;
      let ts = canon (string_of_term w) in
      Printf.fprintf out "CONCL %s\n" ts;
      let asmtext =
        List.fold_left (fun a (_,th) -> a ^ "\n" ^ canon (string_of_term (concl th)))
          "" asl in
      Printf.fprintf out "DIGEST %s\n" (md5 (asmtext ^ "\n==>\n" ^ ts)))
    gl;
  Printf.fprintf out "END %s\n" tag;
  flush out;;

let run_capture tag tm tac =
  set_goal([],tm);
  e tac;
  let (_,gs,_) = hd(!current_goalstack) in
  dump_goals tag gs;;

let report_closed tag =
  let th = top_thm() in
  Printf.fprintf out "CLOSED %s HYP %d CONCLMD5 %s\n"
    tag (List.length (hyp th)) (md5 (canon (string_of_term (concl th))));
  flush out;;

